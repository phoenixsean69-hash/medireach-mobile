export function normalizeZimbabweLanguage(
  value: unknown,
): ZimbabweTextLanguage {
  const key =
    String(
      value ?? "",
    )
      .trim()
      .toLowerCase();

  return (
    ALIASES[key] ??
    "English"
  );
}

export function isZimbabweTextLanguage(
  value: unknown,
): value is ZimbabweTextLanguage {
  return ZIMBABWE_TEXT_LANGUAGES.includes(
    value as ZimbabweTextLanguage,
  );
}

export function zimbabweLanguageDisplayName(
  value: unknown,
) {
  const normalized =
    normalizeZimbabweLanguage(
      value,
    );

  return (
    ZIMBABWE_TEXT_LANGUAGE_OPTIONS.find(
      option =>
        option.value ===
        normalized,
    )?.label ??
    normalized
  );
}

