export function assessmentLanguage(
  value: unknown,
) {
  return normalizeZimbabweLanguage(
    value,
  );
}

export function assessmentT(
  language: AssessmentLanguage,
  text: string,
) {
  if (
    language === "English"
  ) {
    return text;
  }

  return (
    COPY[language]?.[text] ??
    translateZimbabweText(
      text,
      language,
    ) ??
    text
  );
}

