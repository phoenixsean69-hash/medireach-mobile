export function localizedLabel(
  language: AssessmentLanguage,
  map: Record<string, string>,
  code: string,
) {
  const english =
    map[code] ??
    code
      .replace(/_/g, " ")
      .replace(/\b\w/g, value =>
        value.toUpperCase(),
      );

  return assessmentT(
    language,
    english,
  );
}
